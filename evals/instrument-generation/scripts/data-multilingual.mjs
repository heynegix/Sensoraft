function group(
  language,
  category,
  expectedStatus,
  expectedSensor,
  allowedSensors,
  forbiddenSensors,
  difficulty,
  tags,
  reason,
  prompts,
) {
  return {
    language,
    category,
    expectedStatus,
    expectedSensor: expectedSensor ?? null,
    allowedSensors: allowedSensors ?? [],
    forbiddenSensors: forbiddenSensors ?? [],
    difficulty,
    tags,
    reason,
    prompts,
  };
}

